-- =================================================================
-- 0010_whish_payments: Whish Pay integration.
--
-- A payment link minted on behalf of a company via Whish Pay. We are
-- the third party calling Whish (outbound); `external_id` is the numeric
-- reference Whish echoes back on its callback + status lookups. It is a
-- BIGINT IDENTITY so it is unique, numeric, and monotonic as Whish
-- requires. Once a payment is confirmed PAID we write a ledger
-- Transaction whose `external_transaction_id` is this same number, so
-- the existing (source_id, external_transaction_id) unique constraint
-- makes settlement idempotent even if Whish fires the callback twice.
--
-- Tenant-scoped: RLS by company_id, mirroring the other tenant tables.
-- =================================================================

-- ----- 1. Enum -----
CREATE TYPE "WhishPaymentStatus" AS ENUM ('PENDING', 'PAID', 'FAILED', 'EXPIRED');

-- ----- 2. Table -----
CREATE TABLE "whish_payments" (
  "id"                  UUID                        NOT NULL DEFAULT gen_random_uuid(),
  "company_id"          UUID                        NOT NULL,
  "external_id"         BIGINT                      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "callback_token"      TEXT                        NOT NULL,
  "amount"              NUMERIC(20, 8)              NOT NULL,
  "currency"            CHAR(3)                     NOT NULL,
  "invoice"             TEXT                        NOT NULL,
  "status"              "WhishPaymentStatus"        NOT NULL DEFAULT 'PENDING',
  "collect_url"         TEXT,
  "payer_phone_number"  TEXT,
  "transaction_id"      UUID,
  "metadata"            JSONB,
  "paid_at"             TIMESTAMP(6) WITH TIME ZONE,
  "created_at"          TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
  "updated_at"          TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),

  CONSTRAINT "whish_payments_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "whish_payments_amount_pos_chk" CHECK ("amount" > 0),
  CONSTRAINT "whish_payments_company_id_fkey"
    FOREIGN KEY ("company_id")     REFERENCES "companies"    ("id") ON DELETE RESTRICT,
  CONSTRAINT "whish_payments_transaction_id_fkey"
    FOREIGN KEY ("transaction_id") REFERENCES "transactions" ("id") ON DELETE SET NULL
);

CREATE UNIQUE INDEX "whish_payments_external_id_key"     ON "whish_payments" ("external_id");
CREATE UNIQUE INDEX "whish_payments_callback_token_key"  ON "whish_payments" ("callback_token");
CREATE UNIQUE INDEX "whish_payments_transaction_id_key"  ON "whish_payments" ("transaction_id");
CREATE INDEX        "whish_payments_company_status_idx"  ON "whish_payments" ("company_id", "status");
CREATE INDEX        "whish_payments_company_created_idx" ON "whish_payments" ("company_id", "created_at");

-- ----- 3. Row-level security (mirror of the other tenant tables) -----
ALTER TABLE "whish_payments" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "whish_payments_tenant_isolation" ON "whish_payments"
  USING      (app_bypass_rls() OR "company_id" = app_current_company_id())
  WITH CHECK (app_bypass_rls() OR "company_id" = app_current_company_id());

-- ----- 4. Grants — match the existing pattern from 0003_app_rls_role. -----
GRANT SELECT, INSERT, UPDATE, DELETE ON "whish_payments" TO txn_app_rls;

-- ----- 5. Seed the `whish` source (idempotent) so paid payments can be
--         attributed to it and run through the commission engine. -----
INSERT INTO "sources" ("id", "name", "code", "status")
VALUES (gen_random_uuid(), 'Whish Pay', 'whish', 'ACTIVE')
ON CONFLICT ("code") DO NOTHING;
